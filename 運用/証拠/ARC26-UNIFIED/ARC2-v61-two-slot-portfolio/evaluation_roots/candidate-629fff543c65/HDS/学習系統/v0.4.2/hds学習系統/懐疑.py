from __future__ import annotations

from typing import Sequence

from .型 import 経験記録, 懐疑記録


def _推論経路群(経験群: Sequence[経験記録]) -> tuple[tuple[str, ...], ...]:
    return tuple(sorted({o.経路 for e in 経験群 for o in e.観測群 if o.推論対象}, key=repr))


class 標準懐疑器:
    """
    「なぜ？」を疑問文の生成ではなく、所与の成立を再開放し、
    後続の意味操作を起動・制約する懐疑操作として実行する。
    """

    def 作用する(
        self,
        新経験: 経験記録,
        全経験群: Sequence[経験記録],
        時点: str,
        識別子生成,
    ) -> tuple[懐疑記録, ...]:
        全経路 = _推論経路群(全経験群)
        新経路 = tuple(sorted({o.経路 for o in 新経験.観測群 if o.推論対象}, key=repr))
        メタ経路 = tuple(sorted({o.経路 for o in 新経験.観測群 if not o.推論対象}, key=repr))

        仕様 = (
            (
                "成立根拠",
                "現在の観測・関係を所与とせず、どの条件との対応で成立しているかを比較する",
                全経路,
                ("比較", "共通性", "条件関係生成"),
                "推論対象として観測された経路間の成立関係を監査するため",
            ),
            (
                "成立不能条件",
                "既存の説明が崩れる条件・反例を探索し、必要なら条件追加を要求する",
                全経路,
                ("反例探索", "条件追加探索"),
                "単純な説明を固定せず反例と境界を探索するため",
            ),
            (
                "代替関係",
                "一つの説明へ早期収束せず、別の条件集合で同じ観測を説明できないかを比較する",
                全経路,
                ("代替条件探索", "交絡監査"),
                "観測上識別不能な別説明を保持するため",
            ),
            (
                "観測と前提",
                "吸気由来メタ情報と外界観測を分離し、推論対象境界を監査する",
                メタ経路 + 新経路,
                ("推論対象境界監査",),
                "入力装置自身が生成した情報を外界原理へ誤投影しないため",
            ),
            (
                "適用境界",
                "観測済み範囲と未観測値を分け、どこまで転用できるかを監査する",
                全経路,
                ("未観測値監査", "適用範囲監査"),
                "観測範囲を越えた一般化を無言で行わないため",
            ),
        )
        return tuple(
            懐疑記録(
                懐疑識別子=識別子生成("懐疑"),
                経験参照=新経験.経験識別子,
                焦点=焦点,
                作用内容=内容,
                参照経験群=tuple(e.経験識別子 for e in 全経験群),
                時点=時点,
                対象経路群=対象経路群,
                要求操作群=要求操作群,
                発火根拠=発火根拠,
            )
            for 焦点, 内容, 対象経路群, 要求操作群, 発火根拠 in 仕様
        )
