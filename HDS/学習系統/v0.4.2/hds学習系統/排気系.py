from __future__ import annotations

from dataclasses import asdict
from typing import Any

from .型 import 外部出力, 実行結果, 学習成立状態


class 最小排気系:
    """実行結果を再判断せず外部表現へ変換する。"""

    def 排出する(self, 結果: 実行結果) -> 外部出力:
        学習判定保留 = 結果.学習過程.学習成立状態 in {
            学習成立状態.未確認,
            学習成立状態.不成立確認,
        }
        状態 = "断定保留" if (
            結果.競合群
            or 結果.係争中原理群
            or 結果.追加観測要求群
            or 結果.識別不能群
            or 学習判定保留
        ) else "出力"
        内容: dict[str, Any] = {
            "学習成立状態": 結果.学習過程.学習成立状態.value,
            "現在状態版": 結果.現在状態版,
            "予測群": [asdict(x) for x in 結果.予測群],
            "競合群": [asdict(x) for x in 結果.競合群],
            "追加観測要求群": [asdict(x) for x in 結果.追加観測要求群],
            "識別不能群": [asdict(x) for x in 結果.識別不能群],
            "有効原理群": [
                {
                    "原理識別子": x.原理識別子,
                    "版": x.版,
                    "状態": x.状態.value,
                    "採用状態": x.採用状態.value,
                    "関係型": x.関係型,
                    "条件経路群": x.条件経路群,
                    "結果経路": x.結果経路,
                    "適用範囲": dict(x.適用範囲),
                    "親原理参照": x.親原理参照,
                    "改訂理由": x.改訂理由,
                    "除外反証参照群": list(x.除外反証参照群),
                }
                for x in 結果.有効原理群
            ],
            "係争中原理群": [
                {
                    "原理識別子": x.原理識別子,
                    "版": x.版,
                    "状態": x.状態.value,
                    "採用状態": x.採用状態.value,
                    "関係型": x.関係型,
                    "条件経路群": x.条件経路群,
                    "結果経路": x.結果経路,
                    "支持参照群": list(x.根拠参照群),
                    "反証参照群": list(x.反証参照群),
                    "改訂理由": x.改訂理由,
                }
                for x in 結果.係争中原理群
            ],
            "断定保留理由群": list(結果.断定保留理由群),
        }
        return 外部出力(状態=状態, 内容=内容, 追跡情報=dict(結果.追跡情報))
