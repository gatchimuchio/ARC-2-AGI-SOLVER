def 現在時刻() -> str:
    return datetime.now(timezone.utc).isoformat()


class HDS学習実行系:
    """HDS rev4.2 の学習作用を領域非依存で実行する最小共通中核。"""

    def __init__(self, 最小支持数: int = 3, 最大条件数: int = 2, 数量関係有効: bool = True) -> None:
        self.識別子 = 識別子生成器()
        self.台帳 = 追記専用台帳()
        self.状態 = 状態管理器()
        self.懐疑器 = 標準懐疑器()
        self.推論器 = 共通推論器(最大条件数=最大条件数)
        self.最大条件数 = 最大条件数
        self.検証器 = 共通検証器(最小支持数=最小支持数)
        self.適応器 = 共通適応器()
        self.数量関係有効 = 数量関係有効
        self.最小支持数 = 最小支持数
        self._原理履歴: dict[str, list[原理記録]] = {}

    @property
    def 数量関係有効(self):
        return self._数量関係有効

    @数量関係有効.setter
    def 数量関係有効(self, value):
        if type(value) is not bool:
            raise TypeError('数量関係有効は真偽値')
        self._数量関係有効 = value
        self.推論器.数量関係有効 = value
        self.適応器.数量関係有効 = value

    def _次(self, 種別: str) -> str:
        return self.識別子.次(種別)

    def _経験群(self, 対象系境界: str | None = None) -> tuple[経験記録, ...]:
        群 = tuple(x for x in self.台帳.取得("観測台帳") if isinstance(x, 経験記録))
        if 対象系境界 is None:
            return 群
        return tuple(x for x in 群 if x.対象系境界 == 対象系境界)

    def _現行原理群(self) -> tuple[原理記録, ...]:
        状態 = self.状態.現在状態
        結果: list[原理記録] = []
        for 系譜, 原理ID in 状態.items():
            for 原理 in reversed(self._原理履歴.get(系譜, [])):
                if 原理.原理識別子 == 原理ID:
                    結果.append(原理)
                    break
        return tuple(結果)

    def _原理を探す(self, 原理識別子: str) -> 原理記録 | None:
        for 履歴 in self._原理履歴.values():
            for 原理 in reversed(履歴):
                if 原理.原理識別子 == 原理識別子:
                    return 原理
        return None

    @staticmethod
    def _原理は隔離中(原理: 原理記録) -> bool:
        # v0.4.1以前の保存物では原理状態=係争中としていた。
        # v0.4.2以降は正本に合わせ、原理状態と採用状態を分離する。
        return 原理.採用状態 == 採用状態.隔離 or 原理.状態 == 原理状態.係争中

    def _有効原理群(self) -> tuple[原理記録, ...]:
        return tuple(
            x for x in self._現行原理群()
            if x.状態 == 原理状態.適用範囲付き暫定原理
            and x.採用状態 == 採用状態.有効
            and (self.数量関係有効 or x.関係型 != "数量一次関係")
        )

    def _係争中原理群(self) -> tuple[原理記録, ...]:
        return tuple(x for x in self._現行原理群() if self._原理は隔離中(x)
                     and (self.数量関係有効 or x.関係型 != "数量一次関係"))

    def _記憶する(self, 入力: 学習入力, 時点: str) -> 経験記録:
        経験 = 経験記録(
            経験識別子=self._次("経験"),
            対象系境界=入力.対象系境界,
            原入力=入力.原入力,
            観測群=入力.観測群,
            主体=入力.主体,
            対象=入力.対象,
            目的=入力.目的,
            時点=時点,
        )
        self.台帳.追記("観測台帳", 経験)
        self.台帳.追記("認知世界台帳", {
            "経験参照": 経験.経験識別子,
            "対象系境界": 入力.対象系境界,
            "観測経路群": tuple(o.経路 for o in 入力.観測群),
            "主体": 入力.主体,
            "対象": 入力.対象,
            "目的": 入力.目的,
            "暫定性": "既定で暫定",
            "時点": 時点,
        })
        return 経験

    def _原理版を作る(
        self,
        元: 原理記録,
        *,
        状態: 原理状態,
        時点: str,
        採用: 採用状態 | None = None,
        根拠参照群: tuple[str, ...] | None = None,
        反証参照群: tuple[str, ...] | None = None,
        親原理参照: str | None = None,
        改訂理由: str | None = None,
        除外反証参照群: tuple[str, ...] | None = None,
        解決理由: str | None = None,
        解決主体: str | None = None,
    ) -> 原理記録:
        return 原理記録(
            原理識別子=self._次("原理"),
            対象系境界=元.対象系境界,
            系譜識別子=元.系譜識別子,
            版=元.版 + 1,
            状態=状態,
            関係型=元.関係型,
            条件経路群=元.条件経路群,
            結果経路=元.結果経路,
            対応表=元.対応表,
            対応値表=元.対応値表,
            根拠参照群=元.根拠参照群 if 根拠参照群 is None else 根拠参照群,
            反証参照群=元.反証参照群 if 反証参照群 is None else 反証参照群,
            適用範囲=元.適用範囲,
            再開放条件=元.再開放条件,
            時点=時点,
            親原理参照=親原理参照 if 親原理参照 is not None else 元.親原理参照,
            改訂理由=改訂理由,
            除外反証参照群=元.除外反証参照群 if 除外反証参照群 is None else 除外反証参照群,
            解決理由=解決理由 if 解決理由 is not None else 元.解決理由,
            解決主体=解決主体 if 解決主体 is not None else 元.解決主体,
            採用状態=元.採用状態 if 採用 is None else 採用,
        )

    def _既存原理を監査する(self, 新経験: 経験記録, 時点: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
        """
        反例は即削除せず一度だけ係争化する。
        係争後の支持・反証増減は証拠台帳だけへ追記し、原理版・状態版を増殖させない。
        """
        経験群 = self._経験群(新経験.対象系境界)
        新状態 = self.状態.現在状態
        係争化: list[str] = []
        証拠更新: list[str] = []
        変更 = False
        for 原理 in self._現行原理群():
            if 原理.対象系境界 != 新経験.対象系境界:
                continue
            支持, 反証 = 原理証拠を評価する(原理, 経験群)

            if self._原理は隔離中(原理):
                if 支持 != 原理.根拠参照群 or 反証 != 原理.反証参照群:
                    self.台帳.追記("証拠台帳", {
                        "原理参照": 原理.原理識別子,
                        "状態": "係争中・証拠更新",
                        "支持参照群": 支持,
                        "反証参照群": 反証,
                        "注意": "証拠更新のみ。原理版・現行状態は変更しない",
                        "時点": 時点,
                    })
                    証拠更新.append(原理.原理識別子)
                continue

            if (原理.状態 != 原理状態.適用範囲付き暫定原理
                    or 原理.採用状態 != 採用状態.有効
                    or not 反証):
                continue
            係争 = self._原理版を作る(
                原理,
                状態=原理状態.適用範囲付き暫定原理,
                採用=採用状態.隔離,
                時点=時点,
                根拠参照群=支持,
                反証参照群=反証,
                改訂理由="関係意味または観測済み適用範囲に反例が入り、原因未確定のため係争化",
            )
            self._原理履歴.setdefault(原理.系譜識別子, []).append(係争)
            self.台帳.追記("原理台帳", 係争)
            self.台帳.追記("証拠台帳", {
                "原理参照": 係争.原理識別子,
                "状態": "係争中",
                "支持参照群": 支持,
                "反証参照群": 反証,
                "注意": "反例を自動的にノイズ扱いしない",
                "時点": 時点,
            })
            self.台帳.追記("全体帰還台帳", {
                "種別": "反例による係争化",
                "旧原理参照": 原理.原理識別子,
                "新記録参照": 係争.原理識別子,
                "経験参照": 新経験.経験識別子,
                "時点": 時点,
            })
            self.台帳.追記("更新台帳", {
                "更新識別子": self._次("更新"),
                "種別": "反例による隔離",
                "旧原理参照": 原理.原理識別子,
                "原理参照": 係争.原理識別子,
                "採用状態": 係争.採用状態.value,
                "経験参照": 新経験.経験識別子,
                "時点": 時点,
            })
            新状態[原理.系譜識別子] = 係争.原理識別子
            係争化.append(係争.原理識別子)
            変更 = True
        if 変更:
            self.状態.更新(新状態)
        return tuple(係争化), tuple(証拠更新)

    def 係争を解決する(
        self,
        原理識別子: str,
        処置: str,
        理由: str,
        承認主体: str,
        審査対象反証参照群: tuple[str, ...] | None = None,
    ) -> 原理記録:
        """
        隔離された原理の出口。

        復帰では、隔離後に到着した反証を無言で見落とさない。最新証拠を再評価し、
        後着反証がある場合は、その参照群を明示審査対象として完全一致で渡すまで復帰を拒否する。
        観測自体は削除せず、審査済み除外として当該系譜へだけ継承する。
        """
        時点 = 現在時刻()
        原理 = self._原理を探す(原理識別子)
        if 原理 is None:
            raise KeyError(f"原理が見つかりません: {原理識別子}")
        現行 = {x.原理識別子: x for x in self._現行原理群()}
        if 原理識別子 not in 現行 or not self._原理は隔離中(原理):
            raise ValueError("現行の隔離中原理だけを解決できます")
        if not 理由.strip() or not 承認主体.strip():
            raise ValueError("係争解決には理由と承認主体が必要です")

        最新支持, 最新反証 = 原理証拠を評価する(原理, self._経験群(原理.対象系境界))
        既知反証 = set(原理.反証参照群)
        後着反証 = tuple(x for x in 最新反証 if x not in 既知反証)

        新状態 = self.状態.現在状態
        if 処置 == "復帰":
            if 審査対象反証参照群 is None:
                if 後着反証:
                    self.台帳.追記("判断台帳", {
                        "種別": "係争解決保留",
                        "原理参照": 原理.原理識別子,
                        "理由": "隔離後に到着した反証が未審査",
                        "後着反証参照群": 後着反証,
                        "最新反証参照群": 最新反証,
                        "承認主体": 承認主体,
                        "時点": 時点,
                    })
                    raise ValueError(
                        "隔離後の後着反証が未審査です。審査対象反証参照群に最新反証を明示してください: "
                        + ", ".join(後着反証)
                    )
                審査済み反証 = tuple(最新反証)
            else:
                審査済み反証 = tuple(dict.fromkeys(審査対象反証参照群))
                if set(審査済み反証) != set(最新反証):
                    未審査 = tuple(x for x in 最新反証 if x not in set(審査済み反証))
                    余分 = tuple(x for x in 審査済み反証 if x not in set(最新反証))
                    raise ValueError(
                        f"復帰審査は現時点の全反証を対象にする必要があります。未審査={未審査}, 現在反証でない参照={余分}"
                    )

            解決後 = self._原理版を作る(
                原理,
                状態=原理状態.適用範囲付き暫定原理,
                採用=採用状態.有効,
                時点=時点,
                根拠参照群=最新支持,
                反証参照群=(),
                除外反証参照群=tuple(dict.fromkeys(原理.除外反証参照群 + 審査済み反証)),
                改訂理由="隔離を明示審査により復帰",
                解決理由=理由,
                解決主体=承認主体,
            )
            新状態[原理.系譜識別子] = 解決後.原理識別子
        elif 処置 == "棄却":
            解決後 = self._原理版を作る(
                原理,
                状態=原理状態.反証済み,
                採用=採用状態.棄却済み,
                時点=時点,
                根拠参照群=最新支持,
                反証参照群=最新反証,
                改訂理由="隔離を明示審査により棄却",
                解決理由=理由,
                解決主体=承認主体,
            )
            新状態[原理.系譜識別子] = 解決後.原理識別子
            審査済み反証 = tuple(最新反証)
        else:
            raise ValueError("処置は『復帰』または『棄却』です")

        self._原理履歴.setdefault(原理.系譜識別子, []).append(解決後)
        self.台帳.追記("原理台帳", 解決後)
        self.台帳.追記("判断台帳", {
            "種別": "係争解決",
            "旧原理参照": 原理.原理識別子,
            "新原理参照": 解決後.原理識別子,
            "処置": 処置,
            "理由": 理由,
            "承認主体": 承認主体,
            "最新支持参照群": 最新支持,
            "最新反証参照群": 最新反証,
            "後着反証参照群": 後着反証,
            "審査対象反証参照群": 審査済み反証,
            "時点": 時点,
        })
        self.台帳.追記("更新台帳", {
            "更新識別子": self._次("更新"),
            "種別": "隔離解決",
            "旧原理参照": 原理.原理識別子,
            "原理参照": 解決後.原理識別子,
            "処置": 処置,
            "採用状態": 解決後.採用状態.value,
            "時点": 時点,
        })
        self.状態.更新(新状態)
        return 解決後

    def _より単純な同等原理がある(self, 候補, 今回採用候補群=()) -> bool:
        候補条件 = set(候補.条件経路群)
        for 既採用 in 今回採用候補群:
            if 既採用.対象系境界 != 候補.対象系境界 or 既採用.結果経路 != 候補.結果経路:
                continue
            既条件 = set(既採用.条件経路群)
            if len(既条件) < len(候補条件) and 既条件.issubset(候補条件):
                return True
        for 原理 in self._有効原理群():
            if 原理.対象系境界 != 候補.対象系境界 or 原理.結果経路 != 候補.結果経路:
                continue
            原理条件 = set(原理.条件経路群)
            if len(原理条件) < len(候補条件) and 原理条件.issubset(候補条件):
                return True
        return False

    def _親原理を探す(self, 候補) -> 原理記録 | None:
        候補条件 = set(候補.条件経路群)
        候補群: list[原理記録] = []
        for 原理 in self._係争中原理群():
            if 原理.対象系境界 != 候補.対象系境界 or 原理.結果経路 != 候補.結果経路:
                continue
            親条件 = set(原理.条件経路群)
            if 親条件 < 候補条件:
                候補群.append(原理)
        if not 候補群:
            return None
        return sorted(候補群, key=lambda x: (-len(x.条件経路群), x.原理識別子))[0]

    def _親を再開放する(self, 親: 原理記録, 子: 原理記録, 時点: str, 新状態: dict[str, str]) -> str:
        再開放 = self._原理版を作る(
            親,
            状態=原理状態.再開放済み,
            採用=採用状態.新版移行済み,
            時点=時点,
            改訂理由=f"より狭い条件の子原理 {子.原理識別子} へ改訂",
        )
        self._原理履歴.setdefault(親.系譜識別子, []).append(再開放)
        self.台帳.追記("原理台帳", 再開放)
        self.台帳.追記("全体帰還台帳", {
            "種別": "特殊化による親原理再開放",
            "親原理参照": 親.原理識別子,
            "子原理参照": 子.原理識別子,
            "新記録参照": 再開放.原理識別子,
            "時点": 時点,
        })
        self.台帳.追記("更新台帳", {
            "更新識別子": self._次("更新"),
            "種別": "特殊化による親原理再開放",
            "旧原理参照": 親.原理識別子,
            "原理参照": 再開放.原理識別子,
            "子原理参照": 子.原理識別子,
            "時点": 時点,
        })
        新状態.pop(親.系譜識別子, None)
        return 再開放.原理識別子

    def _採用する(self, 候補群, 経験群, 時点: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
        採用ID群: list[str] = []
        再開放ID群: list[str] = []
        今回採用候補群 = []
        新状態 = self.状態.現在状態
        変更 = False
        for 候補 in sorted(候補群, key=lambda x: (len(x.条件経路群), repr(x.条件経路群), repr(x.結果経路))):
            検証 = self.検証器.検証する(候補, 経験群)
            self.台帳.追記("証拠台帳", {
                "候補参照": 候補.候補識別子,
                "判定": 検証.判定.value,
                "理由": 検証.理由,
                "支持参照群": 検証.支持参照群,
                "反証参照群": 検証.反証参照群,
                "時点": 時点,
            })
            self.台帳.追記("判断台帳", {
                "候補参照": 候補.候補識別子,
                "採否": "試行採用" if 検証.判定 == 判定状態.適合 else "保留または隔離",
                "判定": 検証.判定.value,
                "時点": 時点,
            })
            if 検証.判定 != 判定状態.適合:
                continue
            if self._より単純な同等原理がある(候補, 今回採用候補群):
                self.台帳.追記("判断台帳", {
                    "候補参照": 候補.候補識別子,
                    "採否": "保留",
                    "理由": "同じ結果を説明するより少ない条件の有効原理が存在するため冗長採用を保留",
                    "時点": 時点,
                })
                continue

            系譜 = 系譜鍵(候補.対象系境界, 候補.関係型, 候補.条件経路群, 候補.結果経路)
            旧 = self._原理履歴.get(系譜, [])[-1] if self._原理履歴.get(系譜) else None
            if (旧 is not None
                    and 旧.状態 == 原理状態.適用範囲付き暫定原理
                    and 旧.採用状態 == 採用状態.有効
                    and 旧.対応表 == 候補.対応表
                    # 数量の意味は有限表ではなく係数・適用範囲にある。
                    and (候補.関係型 != "数量一次関係" or 旧.適用範囲 == 候補.適用範囲)):
                continue

            親 = self._親原理を探す(候補)
            原理 = self.適応器.原理化する(
                候補,
                旧,
                self._次,
                時点=時点,
                親原理参照=None if 親 is None else 親.原理識別子,
                改訂理由=None if 親 is None else "係争中の広い原理を、反例を説明できる狭い条件へ特殊化",
            )
            self._原理履歴.setdefault(系譜, []).append(原理)
            self.台帳.追記("原理台帳", 原理)
            self.台帳.追記("暫定性台帳", {
                "対象参照": 原理.原理識別子,
                "対象型": "暫定原理",
                "対象系境界": 原理.対象系境界,
                "暫定性状態": "局所安定",
                "再開放条件": 原理.再開放条件,
                "時点": 時点,
            })
            self.台帳.追記("更新台帳", {
                "更新識別子": self._次("更新"),
                "種別": "導出内容の後続処理への反映",
                "原理参照": 原理.原理識別子,
                "系譜": 系譜,
                "旧版": None if 旧 is None else 旧.版,
                "新版": 原理.版,
                "親原理参照": 原理.親原理参照,
                "時点": 時点,
            })
            新状態[系譜] = 原理.原理識別子
            採用ID群.append(原理.原理識別子)
            今回採用候補群.append(候補)
            変更 = True

            if 親 is not None:
                再開放ID群.append(self._親を再開放する(親, 原理, 時点, 新状態))

        if 変更:
            self.状態.更新(新状態)
        return tuple(採用ID群), tuple(再開放ID群)

    def 実行(self, 入力: 学習入力) -> 実行結果:
        時点 = 現在時刻()
        前版 = self.状態.現在版
        前状態 = self.状態.現在状態
        更新開始件数 = self.台帳.件数("更新台帳")
        経験 = self._記憶する(入力, 時点)
        係争化, 証拠更新 = self._既存原理を監査する(経験, 時点)

        経験群 = self._経験群(入力.対象系境界)
        懐疑群 = self.懐疑器.作用する(経験, 経験群, 時点, self._次)
        for 懐疑 in 懐疑群:
            self.台帳.追記("懐疑台帳", 懐疑)

        推論対象観測 = tuple(o for e in 経験群 for o in e.観測群 if o.推論対象)
        候補群 = self.推論器.導出する(
            経験群, 懐疑群, self.最小支持数, self._次, 継続原理群=self._有効原理群()
        ) if 推論対象観測 else ()

        現観測経路群 = tuple(sorted({o.経路 for e in 経験群 for o in e.観測群 if o.推論対象}, key=repr))
        現観測経路数 = len(現観測経路群)
        if 現観測経路数 - 1 > self.最大条件数:
            残差鍵 = (入力.対象系境界, 現観測経路群, self.最大条件数)
            既存 = self.台帳.取得("残差台帳")
            既記録 = any(
                isinstance(x, dict)
                and x.get("種別") == "実装能力境界"
                and (x.get("対象系境界"), tuple(tuple(p) for p in x.get("推論対象観測経路群", ())), x.get("最大条件数")) == 残差鍵
                for x in 既存
            )
            if not 既記録:
                self.台帳.追記("残差台帳", {
                    "残差識別子": self._次("残差"),
                    "種別": "実装能力境界",
                    "対象系境界": 入力.対象系境界,
                    "記述": f"現行推論器は最大{self.最大条件数}条件までの関係を監査する。より高次の関係は未確認残差として保持する。",
                    "推論対象観測経路数": 現観測経路数,
                    "推論対象観測経路群": 現観測経路群,
                    "最大条件数": self.最大条件数,
                    "撤回条件": "推論能力の拡張または別作用による再監査",
                    "時点": 時点,
                })
        for 候補 in 候補群:
            self.台帳.追記("推論記録台帳", {
                "候補参照": 候補.候補識別子,
                "経験参照群": 候補.根拠参照群,
                "懐疑参照群": 候補.懐疑参照群,
                "関係型": 候補.関係型,
                "条件経路群": 候補.条件経路群,
                "結果経路": 候補.結果経路,
                "生成条件": dict(候補.生成条件),
                "時点": 時点,
            })
        採用, 特殊化再開放 = self._採用する(候補群, 経験群, 時点)

        有効原理 = self._有効原理群()
        係争中原理 = self._係争中原理群()
        予測群, 競合群, 追加観測要求群 = self.適応器.予測する(有効原理, 経験)
        識別不能群 = self.適応器.識別不能を検出する(有効原理, 経験群)

        保留理由: list[str] = []
        if 競合群:
            保留理由.append("複数の有効暫定原理が異なる出力を予測したため断定保留")
        if 係争中原理:
            保留理由.append("反例を含み原因未確定の暫定原理を隔離中。自動的にノイズまたは誤りへ確定しない")
        if 追加観測要求群:
            保留理由.append("関連原理の評価に必要な経路または条件値が未観測。未観測を偽として扱わない")
        if 識別不能群:
            保留理由.append("現観測だけでは複数の関係候補を識別できない。予測可能性と原理同定を分離する")

        後版 = self.状態.現在版
        状態変化理由: list[str] = []
        if 採用:
            状態変化理由.append("新規または改訂原理を後続処理へ反映")
        if 係争化:
            状態変化理由.append("反例により現行原理の採用状態を隔離へ更新")
        if 特殊化再開放:
            状態変化理由.append("特殊化により親原理を再開放")
        状態変化 = bool(状態変化理由) and 後版 != 前版

        if not 推論対象観測:
            成立状態 = 学習成立状態.未確認
            保留理由.append("推論対象となる外界観測がなく、学習成立を確認できない")
        elif 状態変化:
            成立状態 = 学習成立状態.成立確認
        elif self.推論器.不成立を確認する(経験群, 懐疑群, self.最小支持数, 有効原理):
            成立状態 = 学習成立状態.不成立確認
            保留理由.append("現行推論能力と指定観測範囲では、保持情報から適応可能な決定的関係が成立しないことを確認")
        else:
            成立状態 = 学習成立状態.接続途上
            if 予測群:
                保留理由.append("既に適応済みの暫定原理が後続処理へ作用したが、この実行では新しい適応は成立していない")
            elif 証拠更新:
                保留理由.append("隔離原理の証拠は更新されたが、後続処理条件は変更していない")
            else:
                保留理由.append("この実行では新しい適応・隔離・再開放は成立していない")

        新規更新 = self.台帳.取得("更新台帳")[更新開始件数:]
        更新参照群 = tuple(
            x.get("更新識別子") for x in 新規更新
            if isinstance(x, dict) and x.get("更新識別子")
        )
        残差群 = tuple(
            x for x in self.台帳.取得("残差台帳")
            if isinstance(x, dict) and x.get("対象系境界") == 入力.対象系境界
        )
        観測限界参照群 = tuple(
            x.get("残差識別子") for x in 残差群 if x.get("残差識別子")
        )
        観測限界 = (
            f"現行の共通推論は決定的対応関係・同値関係の候補生成型推論を中心とする部分射影",
            f"条件関係の主演算は最大{self.最大条件数}条件まで",
        )
        対象期間 = (経験群[0].時点, 時点) if 経験群 else (時点, 時点)

        学習 = 学習過程記録(
            学習識別子=self._次("学習"),
            学習前状態版=前版,
            学習後状態版=後版,
            経験参照=経験.経験識別子,
            懐疑参照群=tuple(x.懐疑識別子 for x in 懐疑群),
            推論候補参照群=tuple(x.候補識別子 for x in 候補群),
            採用原理参照群=採用,
            再開放原理参照群=特殊化再開放,
            学習成立状態=成立状態,
            時点=時点,
            係争化原理参照群=係争化,
            状態変化理由群=tuple(状態変化理由),
            対象系境界=入力.対象系境界,
            主体参照=入力.主体,
            対象期間=対象期間,
            学習前状態スナップショット=前状態,
            保持記憶参照群=tuple(e.経験識別子 for e in 経験群),
            更新記録参照群=更新参照群,
            観測限界=観測限界,
            観測限界参照群=観測限界参照群,
        )
        self.台帳.追記("学習過程台帳", 学習)
        self.台帳.追記("全体帰還台帳", {
            "種別": "実行完了",
            "経験参照": 経験.経験識別子,
            "学習参照": 学習.学習識別子,
            "状態版": 後版,
            "時点": 時点,
        })
        return 実行結果(
            学習過程=学習,
            現在状態版=後版,
            有効原理群=有効原理,
            予測群=予測群,
            競合群=競合群,
            断定保留理由群=tuple(dict.fromkeys(保留理由)),
            追跡情報={
                "経験参照": 経験.経験識別子,
                "対象系境界": 入力.対象系境界,
                "台帳件数": {名: len(値) for 名, 値 in self.台帳.全取得().items()},
            },
            係争中原理群=係争中原理,
            追加観測要求群=追加観測要求群,
            識別不能群=識別不能群,
        )


    def 照会(self, 入力: 学習入力) -> 実行結果:
        """
        学習判定を伴わない純粋な予測照会。

        入力は記憶へ追加せず、懐疑・推論・採否・適応も実行しない。
        現在有効な暫定原理だけを参照して出力を構成するため、学習成立状態は「適用外」とする。
        """
        時点 = 現在時刻()
        照会経験 = 経験記録(
            経験識別子=self._次("照会"),
            対象系境界=入力.対象系境界,
            原入力=入力.原入力,
            観測群=入力.観測群,
            主体=入力.主体,
            対象=入力.対象,
            目的=入力.目的,
            時点=時点,
        )
        有効原理 = self._有効原理群()
        隔離原理 = self._係争中原理群()
        予測群, 競合群, 追加観測要求群 = self.適応器.予測する(有効原理, 照会経験)
        経験群 = self._経験群(入力.対象系境界)
        識別不能群 = self.適応器.識別不能を検出する(有効原理, 経験群)
        保留理由: list[str] = []
        if 競合群:
            保留理由.append("複数の有効暫定原理が異なる出力を予測したため断定保留")
        if 隔離原理:
            保留理由.append("原因未確定で隔離中の原理が存在する")
        if 追加観測要求群:
            保留理由.append("現行暫定原理の適用に必要な観測が不足している")
        if 識別不能群:
            保留理由.append("現観測だけでは複数の関係候補を識別できない")
        学習 = 学習過程記録(
            学習識別子=self._次("学習判定"),
            学習前状態版=self.状態.現在版,
            学習後状態版=self.状態.現在版,
            経験参照=照会経験.経験識別子,
            懐疑参照群=(),
            推論候補参照群=(),
            採用原理参照群=(),
            再開放原理参照群=(),
            学習成立状態=学習成立状態.適用外,
            時点=時点,
            対象系境界=入力.対象系境界,
            主体参照=入力.主体,
            対象期間=(時点, 時点),
            学習前状態スナップショット=self.状態.現在状態,
            保持記憶参照群=tuple(e.経験識別子 for e in 経験群),
            観測限界=("照会経路では学習作用を実行しない",),
        )
        return 実行結果(
            学習過程=学習,
            現在状態版=self.状態.現在版,
            有効原理群=有効原理,
            予測群=予測群,
            競合群=競合群,
            断定保留理由群=tuple(保留理由),
            追跡情報={
                "照会参照": 照会経験.経験識別子,
                "対象系境界": 入力.対象系境界,
                "学習判定": "適用外",
            },
            係争中原理群=隔離原理,
            追加観測要求群=追加観測要求群,
            識別不能群=識別不能群,
        )

    def 保存する(self, 経路: str | Path) -> None:
        書き出す(self, Path(経路))

    @classmethod
    def 読み込む(cls, 経路: str | Path) -> "HDS学習実行系":
        return 読み込む(Path(経路), cls)
